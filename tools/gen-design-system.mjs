#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   docs/design-system.md — GENERATED. Do not hand-edit it.
   ───────────────────────────────────────────────────────────────────────────
   The doc and the live kit come out of ONE registry (app/kit/kit.js), so they
   cannot disagree. Editing the markdown by hand is how a design doc starts
   lying: change the registry instead and re-run this.

     node tools/gen-design-system.mjs

   It serves the repo, drives the kit in headless Chromium, screenshots every
   component, and writes the doc plus docs/design-system/<component>.png.

   ⚠️ It FAILS (exit 1) when the kit's self-check is dirty — a missing helper, a
   FontAwesome CSS-class icon, a native number/colour input, an unskinned
   checkbox, or an emoji used as an icon. That is the point: the doc cannot be
   regenerated while a component breaks the rules the doc states.
   ═══════════════════════════════════════════════════════════════════════════ */
import http from 'http';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_MD = path.join(ROOT, 'docs', 'design-system.md');
const OUT_DIR = path.join(ROOT, 'docs', 'design-system');
const PORT = 8899;
const CHROME = process.env.FTZ_CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const PW = process.env.FTZ_PLAYWRIGHT || '/opt/node22/lib/node_modules/playwright/index.mjs';

const TYPES = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.json': 'application/json' };

const srv = http.createServer((req, res) => {
  let u = decodeURIComponent(req.url.split('?')[0]);
  if (u === '/app/__kit') u = '/app/kit/kit.html';
  const p = path.join(ROOT, u);
  if (!p.startsWith(ROOT) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) {
    res.writeHead(404); return res.end('404');
  }
  res.writeHead(200, { 'Content-Type': TYPES[path.extname(p)] || 'application/octet-stream' });
  res.end(fs.readFileSync(p));
});

// Progress, because this takes a browser launch and 18 screenshots and a
// silent tool that takes 40 seconds looks like a hung one.
const log = (m) => process.stdout.write('  · ' + m + '\n');
await new Promise(r => srv.listen(PORT, r));
const { chromium } = await import(PW);
const browser = await chromium.launch({ executablePath: CHROME });
log('browser up');
const page = await browser.newPage({ viewport: { width: 1240, height: 1400 }, deviceScaleFactor: 1 });  // 1x keeps the doc's images under ~600KB total; the live kit is the real check

const pageErrors = [];
page.on('pageerror', e => pageErrors.push(String(e)));

await page.goto(`http://127.0.0.1:${PORT}/app/__kit`);
await page.waitForSelector('body[data-kit-ready]', { timeout: 20000 });
await page.waitForTimeout(400);
log('kit loaded');

const kit = await page.evaluate(() => ({
  registry: window.__KIT.registry.map(c => ({
    group: c.group, name: c.name, cls: c.cls, note: c.note,
    states: (c.vars || []).map(v => v.label),
    swatches: c.swatches || null,
    icons: c.icons || null,
  })),
  selfCheck: window.__KIT.selfCheck,
  rules: [...document.styleSheets]
    .filter(s => (s.href || '').includes('styles.css'))
    .map(s => { try { return s.cssRules.length; } catch { return -1; } })[0],
}));

// Screenshots, one per component.
fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
log(kit.registry.length + ' components · shooting');
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-');
for (const c of kit.registry) {
  const el = await page.$('#kit-' + slug(c.name));
  if (!el) continue;
  await el.scrollIntoViewIfNeeded();
  await page.waitForTimeout(50);
  await el.screenshot({ path: path.join(OUT_DIR, slug(c.name) + '.png') }).catch(() => {});
}

await browser.close();
srv.close();
log('screenshots written');

// ── The document ──────────────────────────────────────────────────────────
const groups = [];
for (const c of kit.registry) {
  let g = groups.find(x => x.name === c.group);
  if (!g) groups.push(g = { name: c.group, items: [] });
  g.items.push(c);
}

const L = [];
L.push('# Fortized design system');
L.push('');
L.push('> **Generated by `node tools/gen-design-system.mjs`. Do not edit by hand.**');
L.push('> The source is the component registry in `app/kit/kit.js`, which also drives the');
L.push('> live kit at `/app/__kit` (set `FTZ_KIT=1` to serve it). One registry, so the doc');
L.push('> and the page cannot disagree.');
L.push('');
L.push('**If a component is not on this page, it does not exist.** New surfaces get built');
L.push('out of what is here. Inventing a class is how we ended up with six competing');
L.push('visual languages and a user telling us the design does not match.');
L.push('');
L.push(`_${kit.registry.length} components · ${kit.registry.reduce((n, c) => n + c.states.length, 0)} documented states · \`app/styles.css\` parses to ${kit.rules} rules._`);
L.push('');

L.push('## The rules');
L.push('');
L.push('These are not preferences. A component that breaks one of them is a bug.');
L.push('');
L.push('| Rule | Why |');
L.push('| --- | --- |');
L.push('| Icons are **inlined FontAwesome solid SVG paths** via `_faIcon`, never `<i class="fa-…">` | FontAwesome is a CDN dependency; an icon that fails to draw is a broken control |');
L.push('| Never an **emoji as an icon** | An OS emoji is a different typeface on every machine and cannot take our colours |');
L.push('| Controls are **ours**: `_ftzCheckHTML` · `_stfStep` · `_ftzColorPop` · `.ftz-select` · `_stfCal` | A native checkbox, spinner, colour dialog or select is the OS design, not ours |');
L.push('| Thick strokes are **`var(--border)`** | `var(--ink)` is the 3D *button* edge and nothing else |');
L.push('| **No glows.** No coloured blur halo, anywhere | Standing, non-negotiable. A neutral black drop shadow for depth is fine |');
L.push('| **Syne ≤ 700** for anything titled | 800 reads as shouty; the codebase is full of legacy 800s and they get dialled down on contact |');
L.push('| **No em dashes** in user-facing copy | Use a middot. Em dashes read as AI-written |');
L.push('| Every colour comes from a **token** | The appearance system rewrites the tokens at runtime; a hardcoded hex stops recolouring |');
L.push('| Big cards close with **`.settings-close`**, small cards with **`.ftz-close-btn.ftz-ac-x`** | One convention, so the way out of a card is always where you expect |');
L.push('| `animation-fill-mode: backwards`, never `both` | `both` keeps the final keyframe forever and silently swallows the `:hover` lift |');
L.push('');

L.push('## Contents');
L.push('');
for (const g of groups) {
  L.push(`**${g.name}** · ` + g.items.map(c => `[${c.name}](#${slug(c.name)})`).join(' · '));
}
L.push('');

for (const g of groups) {
  L.push(`## ${g.name}`);
  L.push('');
  for (const c of g.items) {
    L.push(`### ${c.name}`);
    L.push('');
    L.push('`' + c.cls + '`');
    L.push('');
    L.push(c.note);
    L.push('');
    if (c.states.length) {
      L.push('**States:** ' + c.states.map(s => '`' + s + '`').join(' · '));
      L.push('');
    }
    if (c.swatches) {
      L.push('**Tokens:** ' + c.swatches.map(s => '`' + s + '`').join(' · '));
      L.push('');
    }
    if (c.icons) {
      L.push(`**${c.icons.length} icons currently inlined:** ` + c.icons.map(s => '`' + s + '`').join(' · '));
      L.push('');
    }
    L.push(`![${c.name}](design-system/${slug(c.name)}.png)`);
    L.push('');
  }
}

// ── Where the debt is ─────────────────────────────────────────────────────
// Run the two guards and fold their real output in, rather than writing a
// number by hand that goes stale the day after it is written.
L.push('## Where the debt is');
L.push('');
L.push('The kit is clean because the kit only contains components that have been rebuilt.');
L.push('The rest of the platform has not, and pretending otherwise is how a design doc');
L.push('starts lying. These are the live counts from `tools/check-icons.mjs` and');
L.push('`tools/check-tokens.mjs`. Every phase of the rework brings them down.');
L.push('');
for (const [tool, label] of [['check-icons.mjs', 'Icons'], ['check-tokens.mjs', 'Colour tokens, type weight and glows']]) {
  let out;
  try {
    out = execFileSync('node', [path.join(ROOT, 'tools', tool)], { encoding: 'utf8', cwd: ROOT });
  } catch (e) {
    out = (e.stdout || '') + (e.stderr || '');   // both guards exit non-zero while debt remains
  }
  L.push(`### ${label}`);
  L.push('');
  L.push('```');
  L.push(out.trimEnd());
  L.push('```');
  L.push('');
}

L.push('## Self-check');
L.push('');
L.push('The kit asserts its own rules against what the components actually rendered.');
L.push('A non-zero count fails the generator, so this doc can only exist while it is clean.');
L.push('');
L.push('| Check | Count |');
L.push('| --- | --- |');
for (const [k, v] of Object.entries(kit.selfCheck)) L.push(`| ${k} | ${v} |`);
L.push('');

fs.writeFileSync(OUT_MD, L.join('\n') + '\n');

const dirty = Object.entries(kit.selfCheck).filter(([, v]) => v > 0);
console.log(`design-system.md written · ${kit.registry.length} components · ${kit.rules} CSS rules`);
if (pageErrors.length) {
  console.error('PAGE ERRORS:\n' + pageErrors.join('\n'));
  process.exit(1);
}
if (dirty.length) {
  console.error('SELF-CHECK DIRTY: ' + dirty.map(([k, v]) => `${k}=${v}`).join(', '));
  process.exit(1);
}
